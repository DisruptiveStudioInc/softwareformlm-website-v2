#!/usr/bin/env python3
"""Normalize saved PSI pages without trusting stale embedded application state.

Run from any directory: python3 performance/extract_reports.py
Only exact JSON timestamps are deduplicated. Minute-rounded visible captures
are retained as observations, never asserted to be independent test runs.
"""
import csv
import html
import json
import re
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent
METRICS = ['first-contentful-paint', 'largest-contentful-paint',
           'total-blocking-time', 'cumulative-layout-shift']


def plain(value):
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]*>', ' ', value))).strip()


def extract(path):
    source = path.read_text()
    embedded = []
    for match in re.finditer(r'"\{\\n\s*\\"fetchTime', source):
        raw, _ = json.JSONDecoder().raw_decode(source[match.start():])
        embedded.append(json.loads(raw))
    conflicts = [r['finalUrl'] for r in embedded if
                 not r['finalUrl'].startswith('https://softwareformlm.com/')]
    starts = list(re.finditer(r'<div class="lh-metric lh-metric--[^\"]+" id="first-contentful-paint">', source))
    if starts:
        # Rendered report wins over cached data for a different page.
        for index, match in enumerate(starts):
            fragment = source[match.start():starts[index + 1].start() if index + 1 < len(starts) else len(source)]
            meta = re.search(r'<ul class="lh-meta__items">(.*?)</ul>', fragment, re.S)
            if not meta:
                raise ValueError(f'Missing device metadata: {path}')
            settings = plain(meta[1])
            mode = 'mobile' if 'Emulated Moto' in settings else 'desktop'
            values = {}
            for metric in METRICS:
                value = re.search(r'<div class="lh-metric lh-metric--[^\"]+" id="' + metric + r'">.*?class="lh-metric__value">(.*?)</div>', fragment, re.S)
                if not value:
                    raise ValueError(f'Missing {metric}: {path}')
                number = float(re.search(r'[\d.,]+', plain(value[1]))[0].replace(',', ''))
                values[metric] = number * (1000 if metric in METRICS[:2] else 1)
            # Read the document URL from the visible network tree, not stale PSI state.
            navigation = re.search(r'Initial Navigation</div>\s*<div[^>]*title="([^"]+)"', fragment)
            url = html.unescape(navigation[1]) if navigation else ''
            if not url.startswith('https://softwareformlm.com/'):
                raise ValueError(f'Unverified visible report URL: {path}')
            date = re.search(r'Captured at (.*?)Emulated', settings)
            version = re.search(r'Lighthouse ([\d.]+)', settings)
            yield dict(file=str(path.relative_to(ROOT)), url=url,
                       device=mode, timestamp=date[1].strip() if date else None,
                       timestamp_precision='minute', version=version[1] if version else None,
                       settings=settings, source='visible-rounded', conflicts=conflicts, **values)
    else:
        for report in embedded:
            if not report['finalUrl'].startswith('https://softwareformlm.com/'):
                continue
            yield dict(file=str(path.relative_to(ROOT)), url=report['finalUrl'],
                       device=report['configSettings']['formFactor'], timestamp=report['fetchTime'],
                       timestamp_precision='millisecond', version=report['lighthouseVersion'],
                       settings=report['configSettings'], source='embedded-json', conflicts=conflicts,
                       **{metric: report['audits'][metric]['numericValue'] for metric in METRICS})


def main():
    paths = sorted([*ROOT.glob('result/*.html'), *ROOT.glob('results_round2/*.html'),
                    *ROOT.glob('PageSpeed-*.html')])
    rows, seen = [], {}
    for path in paths:
        found = list(extract(path))
        if not found:
            raise ValueError(f'No reports extracted: {path}')
        for row in found:
            row['duplicate_of'] = None
            if row['timestamp_precision'] == 'millisecond':
                key = (row['url'], row['device'], row['timestamp'])
                row['duplicate_of'] = seen.get(key)
                seen.setdefault(key, row['file'])
            rows.append(row)
    (ROOT / 'normalized-results.json').write_text(json.dumps(rows, indent=2) + '\n')
    with (ROOT / 'normalized-results.csv').open('w') as output:
        writer = csv.DictWriter(output, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows({**r, 'settings': json.dumps(r['settings']), 'conflicts': json.dumps(r['conflicts'])} for r in rows)
    lines = ['# Corrected archive comparison', '',
             'Generated by `python3 performance/extract_reports.py`. Durations are milliseconds.', '',
             'Exact timestamp duplicates are excluded below. Visible minute-rounded reports remain observations; hidden duplicates may remain. JSON and rounded visible values are mixed. These are lab results, not field percentiles.', '',
             '| Round / device | Observations | LCP median | LCP mean | TBT median | TBT mean | CLS median |',
             '|---|---:|---:|---:|---:|---:|---:|']
    for folder in ['result', 'results_round2']:
        for device in ['mobile', 'desktop']:
            selected = [r for r in rows if r['file'].startswith(folder + '/') and r['device'] == device and not r['duplicate_of']]
            lcp, tbt, cls = ([r[m] for r in selected] for m in METRICS[1:])
            lines.append(f'| {folder} / {device} | {len(selected)} | {statistics.median(lcp):.1f} | {statistics.mean(lcp):.1f} | {statistics.median(tbt):.1f} | {statistics.mean(tbt):.1f} | {statistics.median(cls):.3f} |')
    lines += ['', '## Provenance issues', '']
    for row in rows:
        if row['conflicts']:
            lines.append(f"- {row['file']} ({row['device']}): ignored unrelated embedded URLs {row['conflicts']}; used visible report.")
        if row['duplicate_of']:
            lines.append(f"- {row['file']} ({row['device']}): exact duplicate of {row['duplicate_of']}.")
    lines += ['', 'The previous five-day CSV mixed device modes. Its 6,600 ms outlier belongs to desktop, not mobile. Round two spans one day; round one spans five. Original August 14 PSI reports are retained separately in the normalized data. GTmetrix PDFs use Lighthouse 12.6.1 versus PSI 13.4.1 and must not be pooled with PSI.', '']
    (ROOT / 'corrected-analysis.md').write_text('\n'.join(lines))
    print(f'Extracted {len(rows)} observations from {len(paths)} files.')


if __name__ == '__main__':
    main()
